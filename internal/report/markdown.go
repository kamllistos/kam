package report

import (
	"bufio"
	"fmt"
	"io"
	"strings"

	"github.com/kamllistos/kam/internal/analyze"
)

// Marker is the first line of every markdown report, so CI can find and
// update kam's previous comment on a pull request instead of adding another.
const Marker = "<!-- kam-diff -->"

var emoji = map[analyze.Severity]string{
	analyze.Critical: "🔴",
	analyze.High:     "🟠",
	analyze.Medium:   "🟡",
	analyze.Low:      "🔵",
	analyze.Info:     "⚪",
}

// Markdown writes a report sized for a pull request comment.
func Markdown(w io.Writer, r *analyze.Report) error {
	bw := bufio.NewWriter(w)
	fmt.Fprintln(bw, Marker)
	fmt.Fprintln(bw, "### 🔐 kam diff: IAM access changes")
	fmt.Fprintln(bw)

	switch {
	case r.IAMResources == 0:
		fmt.Fprintln(bw, "No AWS IAM resources in this plan.")
	case len(r.Principals) == 0:
		fmt.Fprintln(bw, "✅ No change to effective IAM access.")
	default:
		fmt.Fprintf(bw, "**%d %s** change access: %s\n\n", len(r.Principals), plural(len(r.Principals), "principal", "principals"),
			summary(r, func(s analyze.Severity, n int) string { return fmt.Sprintf("%s %d %s", emoji[s], n, s) }))

		fmt.Fprintln(bw, "| | Principal | Status | Top finding |")
		fmt.Fprintln(bw, "|---|---|---|---|")
		for _, pd := range r.Principals {
			top := "—"
			if len(pd.Findings) > 0 {
				top = md(pd.Findings[0].Title)
			}
			fmt.Fprintf(bw, "| %s | `%s` | %s | %s |\n", emoji[pd.Severity], pd.Principal.Key, pd.Status, top)
		}
		fmt.Fprintln(bw)

		for _, pd := range r.Principals {
			writePrincipal(bw, pd)
		}
	}

	for _, msg := range r.Warnings {
		fmt.Fprintf(bw, "> ⚠️ %s\n", md(msg))
	}
	fmt.Fprintln(bw)
	fmt.Fprintln(bw, "<sub>Generated by [kam](https://github.com/kamllistos/kam) from the Terraform plan. "+
		"Static analysis: SCPs, permission boundaries and resource-based policies are not evaluated.</sub>")
	return bw.Flush()
}

func writePrincipal(w io.Writer, pd analyze.PrincipalDiff) {
	open := ""
	if pd.Severity >= analyze.High {
		open = " open"
	}
	what := fmt.Sprintf("%d new %s", len(pd.Added), plural(len(pd.Added), "permission", "permissions"))
	if pd.Status == "removed" {
		what = "deleted"
	}
	fmt.Fprintf(w, "<details%s><summary>%s <code>%s</code> · %s</summary>\n\n", open, emoji[pd.Severity], pd.Principal.Key, what)

	for _, f := range pd.Findings {
		fmt.Fprintf(w, "- %s **%s**", emoji[f.Severity], md(f.Title))
		if f.Detail != "" {
			fmt.Fprintf(w, ": %s", md(f.Detail))
		}
		fmt.Fprintln(w)
	}
	if len(pd.Findings) > 0 {
		fmt.Fprintln(w)
	}

	if len(pd.TrustAdded) > 0 {
		fmt.Fprintln(w, "**Can now be assumed by**")
		fmt.Fprintln(w)
		fmt.Fprintln(w, "| | Type | Principal | Condition |")
		fmt.Fprintln(w, "|---|---|---|---|")
		for _, t := range pd.TrustAdded {
			fmt.Fprintf(w, "| %s | %s | `%s` | %s |\n", emoji[t.Severity], t.Type, md(t.Principal), code(t.Condition))
		}
		fmt.Fprintln(w)
	}

	if len(pd.Added) > 0 {
		fmt.Fprintln(w, "**New permissions**")
		fmt.Fprintln(w)
		fmt.Fprintln(w, "| | Action | Resource | Via |")
		fmt.Fprintln(w, "|---|---|---|---|")
		for _, c := range pd.Added {
			action := code(c.Action)
			if c.Opaque {
				action = "_contents not visible_"
			} else if c.Condition != "" {
				action += " _(conditional)_"
			}
			fmt.Fprintf(w, "| %s | %s | %s | %s |\n", emoji[c.Severity], action, code(c.Resource), md(c.Via))
		}
		fmt.Fprintln(w)
	}

	if n := len(pd.Removed) + len(pd.TrustRemoved); n > 0 {
		fmt.Fprintf(w, "_%d %s removed._\n\n", n, plural(n, "permission or trust entry", "permissions or trust entries"))
	}
	fmt.Fprintln(w, "</details>")
	fmt.Fprintln(w)
}

// md escapes text for a markdown table cell.
func md(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ", "<", "&lt;", ">", "&gt;").Replace(s)
}

func code(s string) string {
	if s == "" || s == "?" {
		return "—"
	}
	return "`" + strings.NewReplacer("|", `\|`, "`", "'").Replace(s) + "`"
}
